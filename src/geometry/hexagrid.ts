/**
 * The icosahedral hexagrid, and its dual — PLAN §8.7, step 4.
 *
 * Six families of PLANES in 3-space, normals on the six five-fold axes of an
 * icosahedron, and the dual of their arrangement. It is de Bruijn's
 * construction with one more dimension and nothing else changed: in the plane,
 * a crossing of two lines is dual to a rhomb; in space, an intersection of
 * three planes is dual to a rhombohedron, and
 *
 *     Kⱼ(x) = ⌈x·vⱼ + γⱼ⌉,     f(K) = Σⱼ Kⱼ vⱼ
 *
 * are the same two formulas `pentagrid.ts` has carried all along. Every edge
 * of the dual is one vⱼ, so every edge is unit; every pair of the six axes
 * meets at |cos| = 1/√5, so every face is the golden rhomb — π(C²), the k = 2
 * rung of §8.2's ladder. The tiles are π(C³), of which there are exactly two.
 *
 * **WHY THE SPACING IS THE WHOLE QUESTION HERE.** In the plane you may take
 * the Penrose class from a periodic pentagrid or from the Ammann quasilattice,
 * as you like — §7.5 proved the second dualizes to the first's deflation.
 * Socolar and Steinhardt say that choice does not exist in space: *"In the 3D
 * icosahedral vertex model, the PLI class cannot be generated by duals to
 * periodic hexagrids."* Only the Fibonacci hexagrid gives it, and they give
 * the element — αₙ = 1/τ, βₙ = −½ for all six grids — which §7.4a's dictionary
 * (α = c/T, β = −w/φ) hands straight to `fibonacciLines`. So this module
 * carries both grids and makes the difference measurable rather than quoted:
 * `periodicHexagrid` and `fibonacciHexagrid`, one collector, and a census by
 * intersection order.
 *
 * **AND THE SINGULARITIES ARE NOT RESOLVED, THEY ARE NAMED.** The same paper:
 * *"The 3D Ammann quasilattices are singular in the extreme — anywhere one
 * might have expected an intersection of three planes whose dual is an oblate
 * rhombohedron, additional planes pass through the intersection."* Their
 * answer is to stop resolving and give each order of intersection its own
 * cell, *"and it is actually simpler to describe the structure in terms of the
 * zonohedra"*:
 *
 *     order 3, non-singular   the prolate rhombohedron — the only such dual
 *     order 4                 B12, Bilinski's dodecahedron
 *     order 5                 F20, Fedorov's rhombic icosahedron
 *     order 6                 K30, Kepler's triacontahedron
 *
 * Which is §5.0's arc — a singularity is not a defect, it is a solid — arrived
 * at from the wrong end two months earlier. So `collectCells` groups coincident
 * intersections, counts how many families pass through each, and builds the
 * cell as `zonohedron` of exactly those normals: the cell of an order-k
 * intersection IS π(C^k), with no reading, no nudge and no choice.
 *
 * Nothing here knows about a canvas or about three.js.
 */

import type { LineSet } from "./types.js";
import { fibonacciLines } from "./fibonacci.js";
import { ICO_AXES, zonohedron, cellKind, cellVolume, maskPoint } from "./zono3.js";
import type { Vec3, Zonohedron } from "./zono3.js";

/** Six families, like the pentagrid's five. */
export const HEX_N = 6;

const PHI = (1 + Math.sqrt(5)) / 2;

/**
 * The same tolerance the pentagrid uses on its index function, and for the
 * same reason: a point ON a plane must read as being on it, not past it.
 */
const K_EPS = 1e-9;

/** How close two intersections must be to count as one point. */
const SAME = 1e-7;

/**
 * The gain of the dual map, measured rather than chosen: Σⱼ vⱼvⱼᵀ = 2·I.
 *
 * Six unit vectors spread isotropically in 3-space, so the trace 6 divides by
 * the dimension: n/d = 6/3. The plane's is n/d = 5/2, which is §5.26's
 * registration gain — one formula, two dimensions.
 */
export const DUAL_GAIN = HEX_N / 3;

export interface Hexagrid {
    /** Always 6 here; carried so the formulas read like the pentagrid's. */
    n: number;
    /** The unit normals — the six icosahedral axes. */
    directions: readonly Vec3[];
    /** One offset per family. Σγ is the class, as in the plane. */
    gamma: number[];
    /**
     * Per-family positions, when a family is not periodic. Omitted or a null
     * entry is the periodic family, at n − γⱼ. Same contract as the
     * pentagrid's `lines`, and the same `LineSet`: a position is a number, and
     * a position function does not care how many dimensions its normal has.
     */
    lines?: (LineSet | null)[];
}

/** A box in space, shaped like `ViewRect` one dimension up. */
export interface Box3 {
    xMin: number; xMax: number;
    yMin: number; yMax: number;
    zMin: number; zMax: number;
}

/**
 * One cell of the dual: the solid at one intersection point.
 *
 * `order` is how many families pass through that point — 3 generically, more
 * where the grid is singular — and `solid` names π(C^order). The `zono` is
 * built on exactly the incident normals, so its vertices, faces and edges are
 * the cell's, in the zonohedron's own mask coordinates, and `vertices` is
 * those points placed at `base`.
 */
export interface Cell3 {
    /** Where in the grid the intersection is. */
    at: Vec3;
    /** The cell's base corner in the tiling: f(K) with every incident K low. */
    base: Vec3;
    /** Which families pass through, ascending. */
    families: number[];
    /** How many: 3 where the grid is regular. */
    order: number;
    /** The K-tuple at the base corner. */
    kTuple: number[];
    /** π(C^order), on the incident normals. */
    zono: Zonohedron;
    /** Its vertices, placed. */
    vertices: Vec3[];
    /** Which rhombohedron, for order 3. The two orbits of §8.2. */
    kind?: "acute" | "oblate";
    /** K30, F20, B12, A6 or O6 — the rung of the ladder this cell is. */
    solid: string;
}

/** Where plane n of family j sits: the value of x·vⱼ on it. */
export function planePos(hg: Hexagrid, j: number, n: number): number {
    const set = hg.lines?.[j];
    return set ? set.at(n) : n - hg.gamma[j];
}

/** Which plane of family j a position is at or before — de Bruijn's index. */
export function planeIndexAt(hg: Hexagrid, j: number, t: number): number {
    const set = hg.lines?.[j];
    // The `+ 0` turns Math.ceil's negative zero back into a plane number.
    // `Object.is(-0, 0)` is false, which is what `assert.strictEqual` and a
    // Map key both use, so an index of −0 is a plane that compares equal to
    // nothing — including itself written the other way.
    return set ? set.indexAt(t - K_EPS) : Math.ceil(t + hg.gamma[j] - K_EPS) + 0;
}

const dot3 = (a: Vec3, b: Vec3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross3 = (a: Vec3, b: Vec3): Vec3 => [
    a[1] * b[2] - a[2] * b[1],
    a[2] * b[0] - a[0] * b[2],
    a[0] * b[1] - a[1] * b[0],
];

/** K(x), the hexagrid coordinates of a point. */
export function kTupleAt(hg: Hexagrid, x: Vec3): number[] {
    const K: number[] = [];
    for (let j = 0; j < hg.n; j++) {
        K.push(planeIndexAt(hg, j, dot3(hg.directions[j], x)));
    }
    return K;
}

/** The dual vertex f(K) = Σⱼ Kⱼ vⱼ. */
export function dualVertex(hg: Hexagrid, K: readonly number[]): Vec3 {
    const f: Vec3 = [0, 0, 0];
    for (let j = 0; j < hg.n; j++) {
        const v = hg.directions[j];
        f[0] += K[j] * v[0];
        f[1] += K[j] * v[1];
        f[2] += K[j] * v[2];
    }
    return f;
}

/**
 * Where planes nᵢ, nⱼ, n_k of three families meet. Null if they do not.
 *
 * Cramer, on the 3×3 whose rows are the normals. No two icosahedral axes are
 * parallel and no three are coplanar, so the determinant never vanishes here —
 * the guard is for a caller with its own directions.
 */
export function solveTriple(
    hg: Hexagrid, fams: readonly [number, number, number],
    ns: readonly [number, number, number],
): Vec3 | null {
    const [i, j, k] = fams;
    const a = hg.directions[i], b = hg.directions[j], c = hg.directions[k];
    const bc = cross3(b, c), ca = cross3(c, a), ab = cross3(a, b);
    const det = dot3(a, bc);
    if (Math.abs(det) < 1e-12) return null;
    const pa = planePos(hg, i, ns[0]);
    const pb = planePos(hg, j, ns[1]);
    const pc = planePos(hg, k, ns[2]);
    return [
        (pa * bc[0] + pb * ca[0] + pc * ab[0]) / det,
        (pa * bc[1] + pb * ca[1] + pc * ab[1]) / det,
        (pa * bc[2] + pb * ca[2] + pc * ab[2]) / det,
    ];
}

/** Every three-subset of the six families: twenty. */
const TRIPLES: [number, number, number][] = (() => {
    const out: [number, number, number][] = [];
    for (let i = 0; i < HEX_N; i++) {
        for (let j = i + 1; j < HEX_N; j++) {
            for (let k = j + 1; k < HEX_N; k++) out.push([i, j, k]);
        }
    }
    return out;
})();

/** What π(C^k) is called, by k. §8.2's ladder, named. */
export const SOLID_NAMES: Record<number, string> = {
    3: "A6/O6", 4: "B12", 5: "F20", 6: "K30",
};

/** The range of plane indices of family j that can cross a box. */
function indexRange(hg: Hexagrid, j: number, box: Box3): [number, number] {
    const v = hg.directions[j];
    let lo = Infinity, hi = -Infinity;
    for (const x of [box.xMin, box.xMax]) {
        for (const y of [box.yMin, box.yMax]) {
            for (const z of [box.zMin, box.zMax]) {
                const t = v[0] * x + v[1] * y + v[2] * z;
                if (t < lo) lo = t;
                if (t > hi) hi = t;
            }
        }
    }
    return [planeIndexAt(hg, j, lo), planeIndexAt(hg, j, hi)];
}

const inBox = (p: Vec3, box: Box3, eps = 1e-9) =>
    p[0] >= box.xMin - eps && p[0] <= box.xMax + eps
    && p[1] >= box.yMin - eps && p[1] <= box.yMax + eps
    && p[2] >= box.zMin - eps && p[2] <= box.zMax + eps;

export interface CollectOptions {
    /** Stop after this many planes in one family, as a guard on a huge box. */
    maxPerFamily?: number;
}

/**
 * The dual of the hexagrid over a box: one cell per intersection POINT.
 *
 * Per point, not per triple, and that is the whole of Socolar's prescription.
 * Where four planes meet, the four triples through that point are four views
 * of one intersection, and the cell is π(C⁴) — not four rhombohedra fighting
 * over the same space. So the collector finds points, then asks which families
 * are incident, then builds the solid on exactly those normals.
 *
 * Incidence is asked of all six families at each point rather than taken from
 * the triple that found it, which is what makes the order honest: a family is
 * incident when its own index function puts a plane exactly there.
 */
export function collectCells(
    hg: Hexagrid, box: Box3, opts: CollectOptions = {},
): Cell3[] {
    const cap = opts.maxPerFamily ?? 40;
    const ranges: [number, number][] = [];
    for (let j = 0; j < hg.n; j++) {
        const [lo, hi] = indexRange(hg, j, box);
        ranges.push([lo, Math.min(hi, lo + cap)]);
    }

    /** Points, keyed by position, each carrying nothing but its place. */
    const points = new Map<string, Vec3>();
    const key = (p: Vec3) =>
        `${Math.round(p[0] / SAME)},${Math.round(p[1] / SAME)},${Math.round(p[2] / SAME)}`;

    for (const fams of TRIPLES) {
        const [ri, rj, rk] = [ranges[fams[0]], ranges[fams[1]], ranges[fams[2]]];
        for (let a = ri[0]; a <= ri[1]; a++) {
            for (let b = rj[0]; b <= rj[1]; b++) {
                for (let c = rk[0]; c <= rk[1]; c++) {
                    const p = solveTriple(hg, fams, [a, b, c]);
                    if (!p || !inBox(p, box)) continue;
                    const k = key(p);
                    if (!points.has(k)) points.set(k, p);
                }
            }
        }
    }

    // One zonohedron per set of incident families: there are at most 2^6 of
    // them and a patch uses a handful, so building one per cell would be the
    // same solid thousands of times.
    const solids = new Map<number, Zonohedron>();
    const out: Cell3[] = [];

    for (const p of points.values()) {
        const families: number[] = [];
        const ns: number[] = [];
        const K: number[] = [];
        for (let j = 0; j < hg.n; j++) {
            const t = dot3(hg.directions[j], p);
            const n = planeIndexAt(hg, j, t);
            K.push(n);
            if (Math.abs(planePos(hg, j, n) - t) < SAME) { families.push(j); ns.push(n); }
        }
        if (families.length < 3) continue;        // a rounding artifact, not a cell

        let mask = 0;
        for (const j of families) mask |= 1 << j;
        let zono = solids.get(mask);
        if (!zono) {
            zono = zonohedron(families.map((j) => hg.directions[j]));
            solids.set(mask, zono);
        }
        const base = dualVertex(hg, K);
        const order = families.length;
        const kind = order === 3
            ? cellKind(hg.directions[families[0]], hg.directions[families[1]],
                       hg.directions[families[2]])
            : undefined;
        out.push({
            at: p, base, families, order, kTuple: K, zono,
            vertices: zono.vertices.map((v): Vec3 =>
                [base[0] + v[0], base[1] + v[1], base[2] + v[2]]),
            kind,
            solid: order === 3 ? (kind === "acute" ? "A6" : "O6")
                : SOLID_NAMES[order] ?? `pi(C^${order})`,
        });
    }
    return out;
}

/**
 * Is a point inside this cell?
 *
 * A zonotope is {Σ tᵢ gᵢ : tᵢ ∈ [0,1]}, so it is the intersection of the
 * half-spaces n·x ≤ h(n) over its face normals n = ±gᵢ×gⱼ, where the support
 * function h(n) = Σ max(0, n·gᵢ). Exact, no hull, and it is what says the
 * cells TILE rather than merely exist: sample the region and every point
 * should be in exactly one.
 *
 * A cutaway page (§8.6, page 5) wants the same test, which is why it is here
 * and not in the test that first needed it.
 */
export function cellContains(hg: Hexagrid, cell: Cell3, p: Vec3, eps = 1e-9): boolean {
    const g = cell.families.map((j) => hg.directions[j]);
    const q: Vec3 = [p[0] - cell.base[0], p[1] - cell.base[1], p[2] - cell.base[2]];
    for (let i = 0; i < g.length; i++) {
        for (let j = i + 1; j < g.length; j++) {
            const n0 = cross3(g[i], g[j]);
            for (const sign of [1, -1]) {
                const n: Vec3 = [sign * n0[0], sign * n0[1], sign * n0[2]];
                let h = 0;
                for (const gm of g) { const d = dot3(n, gm); if (d > 0) h += d; }
                if (dot3(n, q) > h + eps) return false;
            }
        }
    }
    return true;
}

/** The volume of a cell: its zonotope's, which is Σ|det| over its triples. */
export function cellVolumeOf(hg: Hexagrid, cell: Cell3): number {
    const g = cell.families.map((j) => hg.directions[j]);
    let v = 0;
    for (let i = 0; i < g.length; i++) {
        for (let j = i + 1; j < g.length; j++) {
            for (let k = j + 1; k < g.length; k++) v += cellVolume(g[i], g[j], g[k]);
        }
    }
    return v;
}

/**
 * The mean plane gap of a Fibonacci family, in units of T.
 *
 * `at(n)` grows like T·n·(1 + 1/φ²), so the dual of a Fibonacci hexagrid at
 * spacing T covers 1/(T·MEAN_GAP)³ of what a unit periodic one covers. At
 * T = 1/MEAN_GAP = 0.7236 the two fill the same space, which is the honest way
 * to compare them.
 */
export const MEAN_GAP = 1 + 1 / (PHI * PHI);

/** How many cells of each order, and of each solid. The census of §8.3. */
export function cellCensus(cells: readonly Cell3[]): Record<string, number> {
    const out: Record<string, number> = {};
    for (const c of cells) out[c.solid] = (out[c.solid] ?? 0) + 1;
    return out;
}

/**
 * The periodic hexagrid: planes at the integers, offset by γ.
 *
 * The one Socolar says cannot give the icosahedral PLI class however γ is
 * chosen. Worth having anyway, and not only as a foil: it is the regular case,
 * so it is where the dual's two rhombohedra can be checked without a
 * singularity anywhere in the patch.
 */
export function periodicHexagrid(gamma?: readonly number[]): Hexagrid {
    const g = gamma ? gamma.slice() : [0.12, -0.31, 0.07, 0.23, -0.17, 0.11];
    return { n: HEX_N, directions: ICO_AXES, gamma: g };
}

/**
 * The Fibonacci hexagrid — Socolar and Steinhardt's own numbers.
 *
 * *"αₙ = 1/τ, βₙ = −½ for all six grids"*, which is the element of the 3D
 * icosahedral PLI class and the only route to it. The same `fibonacciLines`
 * the Ammann bars use, six times: two gaps in the ratio φ, in the Fibonacci
 * word, along each of the six axes.
 *
 * γ is still carried, and is still what `planeIndexAt` would use if a family
 * were handed back to the periodic case — but with all six `lines` set it does
 * not enter. Σγ is not the class here; the cut is.
 */
export function fibonacciHexagrid(
    T = 1, alpha = 1 / PHI, beta = -0.5,
): Hexagrid {
    const lines: LineSet[] = [];
    for (let j = 0; j < HEX_N; j++) lines.push(fibonacciLines(T, alpha, beta));
    return {
        n: HEX_N, directions: ICO_AXES,
        gamma: new Array(HEX_N).fill(0),
        lines,
    };
}

