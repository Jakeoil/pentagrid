#!/usr/bin/env node
/**
 * The container's attribute surface, as a table — the widget's API.
 *
 * Jake, 2026-10-25: *"Where is the API for all the settings of the
 * 'containers' (copy-setup)"* — and there was not one. The data was in
 * `state/inventory.ts` and the names were derivable from it, but nothing
 * rendered them, so the only way to learn what `copy setup` can emit was to
 * read the source. PLAN §9.10 step 2 even claimed the inventory "is also the
 * widget's documentation", which was true of the data and not of the reader.
 *
 * So this generates it, the way `tools/layerchart.mjs` generates the layer
 * chart: printed by default, and `--write` rewrites the marked block in
 * MODULES.md. Generated rather than written, because a hand-kept list of
 * seventy-odd attributes is a list that goes wrong — and the generator reads
 * the same `FIELDS` the reader, the writer and the reset read, so the document
 * cannot disagree with the behavior.
 *
 * Usage: node tools/attrdoc.mjs [--write]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { FIELDS } from "../dist/state/inventory.js";
import { SLICE_ATTRS } from "../dist/state/embed.js";

const BEGIN = "<!-- attrdoc:begin -->";
const END = "<!-- attrdoc:end -->";

/** What a field accepts, said in one cell. */
function accepts(f) {
    if (f.kind === "bool") return "present / `false`";
    if (f.kind === "enum") return f.values.map((v) => `\`${v}\``).join(" · ");
    return "a number";
}
const show = (v) => (v === "" ? "`\"\"`" : `\`${v}\``);

function table(owner, title, note) {
    const mine = FIELDS.filter((f) => f.owner === owner);
    return [
        `### ${title}`,
        "",
        note,
        "",
        "| attribute / parameter | accepts | default |",
        "|---|---|---|",
        ...mine.map((f) => `| \`${f.attr}\` | ${accepts(f)} | ${show(f.fallback)} |`),
    ].join("\n");
}

export function doc() {
    return [
        "Every setting a canvas accepts — as an **attribute** on its container,",
        "and as a **query parameter** on the page. One vocabulary, two spellings:",
        "a parameter may be written with or without the `data-` prefix, since",
        "`?data-color=bands` is the canonical name and `?color=bands` is what",
        "anyone would type. `copy setup` emits the attributes; `copy link` emits",
        "the parameters.",
        "",
        "They are read in this order, each outranking the one after:",
        "",
        "| | |",
        "|---|---|",
        "| the query string | a link says *show me exactly this*, so it wins |",
        "| the session | where you left this page, if it opted in |",
        "| the container's attributes | the page's own setup, and what `reset page` returns to |",
        "| the page's config, then the defaults | |",
        "",
        "A link **suppresses the session** for that load, or a link you shared",
        "would arrive wearing the recipient's last visit. Nothing ever writes the",
        "address bar.",
        "",
        "Generated by `tools/attrdoc.mjs` from `src/state/inventory.ts` — the same",
        "list the reader, the writer and the reset read, so this cannot disagree",
        "with what the code does. Regenerate with `node tools/attrdoc.mjs --write`.",
        "",
        "A **boolean** follows HTML: present is true, and only `false`, `0`, `off`",
        "or `no` are false. Anything that does not parse is **ignored**, and the",
        "field takes its default — so an older embed meets a newer page without",
        "rotting. An attribute that is absent is a default too, which is why",
        "`copy setup` emits only what differs from the page's own baseline.",
        "",
        `**${FIELDS.length} fields** in all: ` +
        `${FIELDS.filter((f) => f.kind === "bool").length} booleans, ` +
        `${FIELDS.filter((f) => f.kind === "enum").length} enums, ` +
        `${FIELDS.filter((f) => f.kind === "number").length} numbers.`,
        "",
        table("features", "Features — which layers exist",
              "What the page draws at all. Each one switches a layer or a hover."),
        "",
        table("tileStyle", "Tile style — how the tiles are dressed",
              "The Penrose side's dressings: colors, the decorations, the shading."),
        "",
        table("grid", "Grid — how the gridlines themselves draw",
              "The reticulum's own lines, not the tiling's. Two knobs that"
              + " belonged to no owner until PLAN §10.4 gave them one."),
        "",
        table("growth", "Growth — the roof and grow pages",
              "`roof.html`, `grow.html` and `grow7.html` only. Three names carry a"
              + " `growth-` prefix because a roof page has a tile style as well, and"
              + " `data-band` would otherwise be ambiguous."),
        "",
        "### The shaped slices",
        "",
        "γ, the view and the layer visibility are not flat fields, so they have",
        "their own attributes. γ is written as **integer numerators over a**",
        "**denominator**, which is how `GammaSet` holds it — so an embed",
        "round-trips γ exactly and `provenRegular` decides the same way on the",
        "far side. It is all-or-nothing: numerators without a denominator are",
        "refused rather than guessed, because half a grid is not a grid.",
        "",
        "| attribute | what it carries |",
        "|---|---|",
        `| \`${SLICE_ATTRS.gamma}\` | the numerators, comma separated: \`2000,2000,2000,2000,2000\` |`,
        `| \`${SLICE_ATTRS.den}\` | their denominator. Required with the above |`,
        `| \`${SLICE_ATTRS.locked}\` | which index is held to keep Σγ, or \`-1\` for none |`,
        `| \`${SLICE_ATTRS.generation}\` | the generation m, where λ = φᵐ |`,
        `| \`${SLICE_ATTRS.symmetry}\` | the offsets move together |`,
        `| \`${SLICE_ATTRS.guard}\` | nudge γ off the singular set |`,
        `| \`${SLICE_ATTRS.off}\` | families switched off, by index: \`3,4\` |`,
        `| \`${SLICE_ATTRS.lines}\` | a family held to one line: \`1:2\` |`,
        `| \`${SLICE_ATTRS.isolated}\` | the isolated family, or empty for none |`,
        `| \`${SLICE_ATTRS.scale}\` | pixels per tiling unit |`,
        `| \`${SLICE_ATTRS.viewX}\`, \`${SLICE_ATTRS.viewY}\` | the pan, in tiling units |`,
        `| \`${SLICE_ATTRS.hide}\` | layers switched off, by id: \`klabels,dots\` |`,
        "",
        "And three that size the canvas rather than style the drawing, read by",
        "`readCanvasSpec` and older than all of the above:",
        "",
        "| attribute | what it carries |",
        "|---|---|",
        "| `data-width`, `data-height` | the canvas in pixels. Absent: the element's own size |",
        "| `data-margin` | the gutter the K-labels live in. Absent: 5% of the lesser side |",
    ].join("\n");
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
    const out = doc();
    if (process.argv.includes("--write")) {
        const p = new URL("../MODULES.md", import.meta.url).pathname;
        const md = readFileSync(p, "utf8");
        const i = md.indexOf(BEGIN), j = md.indexOf(END);
        if (i < 0 || j < 0) throw new Error("MODULES.md has no attrdoc block");
        writeFileSync(p, md.slice(0, i + BEGIN.length) + "\n" + out + "\n" + md.slice(j));
        console.log("MODULES.md updated");
    } else {
        console.log(out);
    }
}
