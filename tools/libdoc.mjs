// Writes the table of dist modules behind each `lib/` entry into lib/README.md.
//
//   node tools/libdoc.mjs            # check, exit 1 if stale
//   node tools/libdoc.mjs --write    # regenerate
//
// Jake, 2026-11-12: "Document the dist files the best you can." The difficulty
// is that `dist/` is BUILT and gitignored (LIBRARY.md §6), so a consumer
// reading this repo on GitHub sees `lib/grow.js` re-exporting from files that
// are not there, and a consumer reading the deployed site sees compiled
// JavaScript with the types erased and the comments stripped. Neither can see
// what is actually in there.
//
// So the table is generated from the TypeScript the build consumes: every dist
// path any entry names, its source's line count, its own first sentence, and
// whether it touches the DOM. Generated rather than written, because a hand
// table about generated files is two things that can go stale instead of one.
// `tools/surface.test.mjs` fails when this file and lib/README.md disagree.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const BEGIN = "<!-- libdoc:begin -->";
const END = "<!-- libdoc:end -->";

/** The dist paths an entry re-exports from, in the order it names them. */
function targets(js) {
    const code = js.split("\n").filter((l) => !l.trimStart().startsWith("//")).join("\n");
    return [...new Set([...code.matchAll(/from\s+"\.\.\/dist\/([^"]+)"/g)].map((m) => m[1]))];
}

/** The exported names an entry promises. */
function names(js) {
    const code = js.split("\n").filter((l) => !l.trimStart().startsWith("//")).join("\n");
    return [...code.matchAll(/export\s+\{([^}]*)\}/g)]
        .flatMap((m) => m[1].split(",").map((s) => s.trim()).filter(Boolean))
        .filter((n) => !n.startsWith("type "));
}

/**
 * A module's own first sentence, off its header comment.
 *
 * The header is not always at the top of the file: `ui/dials.ts` puts an
 * import first, and taking only line 1 left its row blank. So the search is
 * for the first comment block before any code that is not an import.
 */
function sentence(src) {
    const body = src.replace(/^(?:\s*import[^;]*;\s*)+/, "");
    const head = body.match(/^\s*\/\*\*?([\s\S]*?)\*\//) ?? body.match(/^((?:\s*\/\/.*\n)+)/);
    if (!head) return "";
    const text = head[1]
        .split("\n")
        .map((l) => l.replace(/^\s*(\*|\/\/)\s?/, "").trim())
        .join(" ")
        .trim();
    const stop = text.search(/\.\s|\. *$/);
    return (stop > 0 ? text.slice(0, stop + 1) : text).replace(/\s+/g, " ").trim();
}

const entries = readdirSync("lib").filter((f) => f.endsWith(".js")).sort();
const rows = [];
const seen = new Map();
for (const f of entries) {
    const js = readFileSync(`lib/${f}`, "utf8");
    for (const t of targets(js)) {
        const ts = `src/${t.replace(/\.js$/, ".ts")}`;
        let src = "";
        try { src = readFileSync(ts, "utf8"); } catch { /* reported as a gap */ }
        const dom = /document\.|window\.|HTMLElement|CanvasRenderingContext|localStorage/
            .test(src.split("\n").filter((l) => !/^\s*(\*|\/\/)/.test(l)).join("\n"));
        const was = seen.get(t);
        if (was) { was.by.push(f); continue; }
        const row = {
            dist: `dist/${t}`, ts, by: [f],
            lines: src ? src.split("\n").length : 0,
            dom, what: sentence(src),
        };
        seen.set(t, row);
        rows.push(row);
    }
}

const table = [
    "| dist module | source | lines | DOM | what it is |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| \`${r.dist}\` | \`${r.ts}\` | ${r.lines} | ${r.dom ? "yes" : "no"} | ${r.what} |`),
].join("\n");

const byEntry = entries.map((f) => {
    const js = readFileSync(`lib/${f}`, "utf8");
    const t = targets(js).map((x) => `\`dist/${x}\``).join(", ");
    return `- **\`lib/${f}\`** — ${names(js).length} names, over ${t}`;
}).join("\n");

const block = [
    BEGIN,
    `Generated by \`node tools/libdoc.mjs --write\` from the entries in \`lib/\``,
    "and the TypeScript behind them. Do not edit between the markers.",
    "",
    `**${entries.length} entries**, over **${rows.length} modules** of \`dist/\`.`,
    "",
    byEntry,
    "",
    table,
    "",
    END,
].join("\n");

const path = "lib/README.md";
let doc = "";
try { doc = readFileSync(path, "utf8"); } catch { doc = ""; }
const next = doc.includes(BEGIN)
    ? doc.slice(0, doc.indexOf(BEGIN)) + block + doc.slice(doc.indexOf(END) + END.length)
    : doc + (doc ? "\n\n" : "") + block + "\n";

if (process.argv.includes("--write")) {
    writeFileSync(path, next);
    console.log(`lib/README.md: ${rows.length} modules behind ${entries.length} entries`);
} else if (next !== doc) {
    console.error("lib/README.md is out of date — run: node tools/libdoc.mjs --write");
    process.exit(1);
} else {
    console.log("lib/README.md is current");
}
export { targets, names, sentence };
